package com.eeck.server.features.auth.service

import com.eeck.server.core.http.AccessCredentials
import com.eeck.server.core.http.StaticAccessKeys
import com.eeck.server.features.auth.model.AccessMode
import com.eeck.server.features.auth.model.PasswordHasher
import com.eeck.server.features.auth.model.Tokens
import com.eeck.server.features.auth.store.AuthFileStore
import java.security.SecureRandom
import java.util.concurrent.ConcurrentHashMap
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec
import kotlin.time.Duration.Companion.days
import kotlin.time.Duration.Companion.hours
import kotlin.time.Duration.Companion.minutes

data class AuthSettings(
    val userIdleMillis: Long = 1.days.inWholeMilliseconds,
    val userMaxMillis: Long = 7.days.inWholeMilliseconds,
    val adminIdleMillis: Long = 30.minutes.inWholeMilliseconds,
    val adminMaxMillis: Long = 8.hours.inWholeMilliseconds,
)

enum class PasswordSource { ADMIN_PANEL, ENVIRONMENT, NONE }

enum class LoginMethod { PASSWORD, ONE_TIME_CODE }

sealed interface LoginResult {
    data class Success(val token: String, val method: LoginMethod, val expiresAtMillis: Long) : LoginResult

    data object Rejected : LoginResult
}

sealed interface ChangePasswordResult {
    data class Changed(val signedOut: Int) : ChangePasswordResult

    data class Invalid(val reason: String) : ChangePasswordResult
}

data class AuthStatus(
    val accessRequired: Boolean,
    val accessMode: AccessMode,
    val hasPassword: Boolean,
    /** False only for a password from an older version, which is stored as a hash and cannot be shown. */
    val passwordViewable: Boolean,
    val passwordSource: PasswordSource,
    val masterKeyFromEnvironment: Boolean,
    val userSessions: Int,
    val activeCodes: Int,
)

/**
 * Who may use the server, and who may administer it.
 *
 * Two separate secrets, never interchangeable:
 *  - the **server password** (set in `EECK_ACCESS_KEY` or, once changed, in the
 *    admin panel) and **one-time codes** both open the chat server. Either is
 *    exchanged at [login] for a session token, which is what clients send from
 *    then on — so a one-time code is spent exactly once, at sign-in.
 *  - the **master key** opens the admin panel and nothing else.
 *
 * Also the [AccessCredentials] the request gate consults: a user session token, or
 * the password itself (kept working for scripts that send it in a header).
 */
class AuthService(
    private val envPasswords: List<String>,
    private val envMasterKey: String?,
    private val store: AuthFileStore,
    private val clock: () -> Long = System::currentTimeMillis,
    settings: AuthSettings = AuthSettings(),
) : AccessCredentials {

    private val lock = Any()

    @Volatile
    private var state = store.load()
    private val envPassword = StaticAccessKeys(envPasswords)

    private val userSessions = SessionRegistry(clock, settings.userIdleMillis, settings.userMaxMillis)
    private val adminSessions = SessionRegistry(clock, settings.adminIdleMillis, settings.adminMaxMillis)
    val codes = OneTimeCodes(clock, clashesWithPassword = ::passwordMatches)

    /** Remembers (as an HMAC, never the text) passwords already verified, so a script sending one per request pays the slow hash once. */
    private val cacheKey = ByteArray(32).also(SecureRandom()::nextBytes)
    private val verifiedPasswords = ConcurrentHashMap.newKeySet<String>()

    /**
     * With no `EECK_MASTER_KEY`, a fresh random key for this run only: it is printed in the log at
     * start, kept in memory, never written to disk, and different after every restart. Nothing is
     * created on disk for it, so an operator who wants a stable key sets it in `.env`.
     */
    val autoGeneratedMasterKey: String? =
        if (envMasterKey == null) Tokens.fromAlphabet(MASTER_KEY_ALPHABET, GENERATED_MASTER_KEY_LENGTH) else null

    private val master = StaticAccessKeys(listOfNotNull(envMasterKey ?: autoGeneratedMasterKey))

    // ---- the gate -------------------------------------------------------------------------

    private val hasPassword: Boolean get() = state.passwordText != null || state.password != null || envPassword.required

    /** The chosen mode, or — if none was ever chosen — protected exactly when a password exists. */
    val accessMode: AccessMode
        get() = state.access ?: if (hasPassword) AccessMode.PROTECTED else AccessMode.OPEN

    override val required: Boolean get() = accessMode == AccessMode.PROTECTED

    override fun accepts(provided: String): Boolean = userSessions.find(provided) != null || passwordMatches(provided)

    // ---- signing in to the server -------------------------------------------------------

    fun login(secret: String): LoginResult {
        val attempt = secret.trim()
        if (attempt.isEmpty()) return LoginResult.Rejected
        // Codes first: a hash lookup, so a wrong guess costs nothing, whereas the password check is deliberately slow.
        val method = when {
            codes.redeem(attempt) -> LoginMethod.ONE_TIME_CODE
            passwordMatches(secret) -> LoginMethod.PASSWORD
            else -> return LoginResult.Rejected
        }
        val (token, session) = userSessions.create(SessionKind.USER)
        return LoginResult.Success(token, method, session.expiresAtMillis)
    }

    fun logout(token: String) = userSessions.revoke(token)

    // ---- administration -------------------------------------------------------------------

    /** A new admin session as (token, session) if [masterKey] is right. */
    fun adminLogin(masterKey: String): Pair<String, Session>? =
        if (masterKeyMatches(masterKey)) adminSessions.create(SessionKind.ADMIN) else null

    fun adminSession(token: String): Session? = adminSessions.find(token)

    fun adminLogout(token: String) = adminSessions.revoke(token)

    fun status(): AuthStatus = AuthStatus(
        accessRequired = required,
        accessMode = accessMode,
        hasPassword = hasPassword,
        passwordViewable = state.password == null || state.passwordText != null,
        passwordSource = when {
            state.passwordText != null || state.password != null -> PasswordSource.ADMIN_PANEL
            envPassword.required -> PasswordSource.ENVIRONMENT
            else -> PasswordSource.NONE
        },
        masterKeyFromEnvironment = envMasterKey != null,
        userSessions = userSessions.count(SessionKind.USER),
        activeCodes = codes.active().size,
    )

    fun changePassword(newPassword: String, signOutEveryone: Boolean): ChangePasswordResult {
        SecretPolicy.problemWith(newPassword)?.let { return ChangePasswordResult.Invalid(it) }
        synchronized(lock) {
            // The new text replaces whatever an older version stored as a hash.
            state = state.copy(passwordText = newPassword, password = null)
            store.save(state)
            verifiedPasswords.clear()
        }
        return ChangePasswordResult.Changed(if (signOutEveryone) userSessions.revokeAll(SessionKind.USER) else 0)
    }

    /**
     * Opens the server to everyone, or requires a password or code again. Nothing is forgotten
     * either way: the password and unspent codes are kept for when it is protected again, and
     * sessions stay valid. Someone already connected is not dropped by a change; the rule applies
     * to whoever connects next.
     */
    fun setAccessMode(mode: AccessMode) {
        synchronized(lock) {
            state = state.copy(access = mode)
            store.save(state)
        }
    }

    fun signOutEveryone(): Int = userSessions.revokeAll(SessionKind.USER)

    /** [ttlSeconds] is clamped into the allowed range by the caller; this refuses what is outside it. */
    fun createCode(typed: String?, ttlSeconds: Long, label: String): CreateCodeResult {
        if (ttlSeconds !in MIN_CODE_TTL_SECONDS..MAX_CODE_TTL_SECONDS) {
            return CreateCodeResult.Invalid("Choose a lifetime between a minute and a year.")
        }
        return codes.create(typed?.takeIf { it.isNotEmpty() }, ttlSeconds * 1000, label)
    }

    // ---- secrets --------------------------------------------------------------------------

    /**
     * The server password as the panel shows it on request: the one set there, or the one(s) in the
     * environment. Null when there is none, or when it is an older hash that cannot be turned back.
     */
    fun revealPassword(): String? = when {
        state.passwordText != null -> state.passwordText
        state.password != null -> null
        else -> envPasswords.takeIf { it.isNotEmpty() }?.joinToString(", ")
    }

    private fun passwordMatches(candidate: String): Boolean {
        state.passwordText?.let { return StaticAccessKeys(listOf(it)).accepts(candidate) }
        val stored = state.password ?: return envPassword.accepts(candidate)
        val fingerprint = fingerprint(candidate)
        if (fingerprint in verifiedPasswords) return true
        if (!PasswordHasher.verify(candidate, stored)) return false
        if (verifiedPasswords.size >= MAX_CACHED) verifiedPasswords.clear()
        verifiedPasswords.add(fingerprint)
        return true
    }

    private fun masterKeyMatches(candidate: String): Boolean {
        return master.accepts(candidate)
    }

    private fun fingerprint(candidate: String): String {
        val mac = Mac.getInstance("HmacSHA256").apply { init(SecretKeySpec(cacheKey, "HmacSHA256")) }
        return mac.doFinal(candidate.toByteArray()).joinToString("") { "%02x".format(it) }
    }

    companion object {
        const val MIN_CODE_TTL_SECONDS = 60L
        const val MAX_CODE_TTL_SECONDS = 365 * 24 * 60 * 60L
        /** What the panel preselects, and what a form without a lifetime gets: one month. */
        const val DEFAULT_CODE_TTL_SECONDS = 30 * 24 * 60 * 60L
        private const val MAX_CACHED = 256
        private const val GENERATED_MASTER_KEY_LENGTH = 32
        private const val MASTER_KEY_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789"
    }
}
